async function syncBatch6() {
  console.log(`Starting Batch 6 Sync: ${batch6Products.length} products...`);
  
  let count = 0;
  let errors = 0;

  for (const item of batch6Products) {
    try {
      const { data: existing } = await supabaseAdmin
        .from("products")
        .select("id")
        .ilike("name", item.name)
        .limit(1);

      const productPayload: any = {
        name: item.name,
        generic_name: item.generic_name,
        strength: item.strength,
        pack_size: item.pack_size,
        category_name_fallback: item.category_name_fallback || "General",
        mrp: item.mrp,
        selling_price: item.selling_price,
        company: item.company,
        stock_quantity: item.stock_quantity
      };

      if (existing && existing.length > 0) {
        const id = existing[0].id;
        const { error: updErr } = await supabaseAdmin.from("products").update(productPayload).eq("id", id);
        if (updErr) {
          console.error(`Error updating ${item.name}:`, updErr.message);
          errors++;
        } else {
          await supabaseAdmin.from("inventory").upsert({
            product_id: id,
            available_stock: item.stock_quantity,
            expiry_date: "2027-12-31"
          }, { onConflict: "product_id" });
          count++;
        }
      } else {
        const { data: inserted, error: insErr } = await supabaseAdmin
          .from("products")
          .insert(productPayload)
          .select("id")
          .single();

        if (inserted) {
          await supabaseAdmin.from("inventory").insert({
            product_id: inserted.id,
            available_stock: item.stock_quantity,
            reserved_stock: 0,
            sold_stock: 0,
            batch_number: `B-${Math.floor(10000 + Math.random() * 90000)}`,
            expiry_date: "2027-12-31"
          });
          count++;
        } else if (insErr) {
          console.error(`Error inserting ${item.name}:`, insErr.message);
          errors++;
        }
      }
    } catch (err: any) {
      console.error(`Exception processing ${item.name}:`, err.message);
      errors++;
    }
  }

  console.log(`\n=== Batch 6 Sync Complete ===`);
  console.log(`Total Products Synced: ${count}`);
  console.log(`Errors: ${errors}`);
}

syncBatch6().catch(console.error);

